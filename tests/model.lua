local EW={enabled=true,cap=5}
assert(loadfile("ExecutionerWatch/Model.lua"))("ExecutionerWatch",EW)
local M=EW.Model
local tests=0
local function test(name,run)
  run(); tests=tests+1; print("PASS "..name)
end
local function eq(actual,expected) assert(actual==expected,tostring(actual).." ~= "..tostring(expected)) end
test("one proc, five slots, overflow, ordered expiries",function()
  local m=M.New(18)
  for t=1,6 do m:Cast(t) end
  eq(m.count,5); eq(m:Debt(),1)
  m:Advance(19)
  eq(m.count,4); eq(m:Debt(),1)
  eq(m:Snapshot().rows[1].expiresAt,20)
end)
test("application + cast 100ms apart in either order count once",function()
  local m=M.New(18)
  m:Applied(1); m:Cast(1.1); eq(m.count,1)
  m:Reset(2); m:Cast(3); m:Applied(3.1); eq(m.count,1)
end)
test("two distinct casts within correlation window count twice",function()
  local m=M.New(18)
  m:Applied(1); m:Cast(1.05); m:Cast(1.10); eq(m.count,2)
end)
test("unknown update invalidates timeline instead of inventing gain",function()
  local m=M.New(18)
  m:Cast(1); m:Updated(2)
  eq(m.state,"UNCERTAIN"); eq(m:Debt(),0); eq(#m:Snapshot().rows,0)
end)
test("removal resets even an empty uncertain queue",function()
  local m=M.New(18)
  m:Uncertain(1,"lost"); m:Reset(2,"removed"); m:Applied(3)
  eq(m.state,"ACTIVE"); eq(m.count,1)
end)
test("expiry and proc at same instant preserve new timer",function()
  local m=M.New(18)
  m:Cast(1); m:Cast(19)
  eq(m.count,1); eq(m:Snapshot().rows[1].expiresAt,37)
end)
test("multiple simultaneous expiries are all consumed",function()
  local m=M.New(18)
  m:Cast(1); m:Cast(1); m:Cast(2); m:Advance(19)
  eq(m.count,1); eq(#m.queue,1)
end)
test("expiry-near update does not consume another layer",function()
  local m=M.New(18)
  m:Cast(1); m:Cast(2); m:Updated(19.05); m:Advance(19.1)
  eq(m.state,"ACTIVE"); eq(m.count,1)
end)
test("multi-stack reload does not manufacture independent timers",function()
  local m=M.New(18)
  m:Observe(10,3,18,20); eq(m.state,"UNCERTAIN")
  m:Observe(11,0); m:Applied(12); eq(m.count,1)
end)
test("readable single stack can be synchronized",function()
  local m=M.New(18)
  m:Uncertain(2,"reload"); m:Observe(10,1,18,20)
  eq(m.state,"ACTIVE"); eq(m:Snapshot().rows[1].expiresAt,20)
end)
test("aggregate expiration is not used as a per-stack oracle",function()
  local m=M.New(18)
  m:Cast(1); m:Cast(2); m:Observe(3,2,18,99)
  eq(m.state,"ACTIVE")
  m:Observe(3,3,18,99); eq(m.state,"UNCERTAIN")
end)
test("snapshot mutation does not modify model",function()
  local m=M.New(18); m:Cast(1)
  local s=m:Snapshot(); s.rows[1].expiresAt=0
  eq(m.queue[1].expiresAt,19)
end)
test("early native removal consumes predicted expiry only once",function()
  local m=M.New(18); m:Applied(1); m:TargetRefresh(2)
  m:TargetRefresh(18.9); eq(m.count,1)
  m:Advance(19.05); eq(m.count,1)
end)
test("late native removal acknowledges an already consumed expiry",function()
  local m=M.New(18); m:Applied(1); m:TargetRefresh(2)
  m:Advance(19.02); eq(m.count,1)
  m:TargetRefresh(19.1); eq(m.count,1); eq(m:Debt(),0)
end)
test("targeted refresh cannot reconstruct a missing multi-stack timeline",function()
  local m=M.New(18); m:Uncertain(1,'missing')
  m:TargetRefresh(2); eq(m.state,'UNCERTAIN'); eq(m.count,0)
  m:Applied(3); eq(m.state,'ACTIVE'); eq(m.count,1)
end)
test("overflow timer moves inside on gain without resetting its expiration",function()
  local m=M.New(18)
  for t=1,6 do m:Add(t,"fixture") end
  local before=m:Snapshot()
  local overflowID=before.debtRows[1].id
  eq(before.debtRows[1].expiresAt,24)
  m:Advance(19)
  local dropped=m:Snapshot()
  eq(dropped.count,4); eq(dropped.debt,1)
  eq(dropped.debtRows[1].id,overflowID)
  m:Add(19.5,"fixture")
  local gained=m:Snapshot()
  eq(gained.count,5); eq(gained.debt,1)
  eq(gained.rows[5].id,overflowID); eq(gained.rows[5].expiresAt,24)
  eq(gained.debtRows[1].expiresAt,37.5)
  gained.debtRows[1].expiresAt=0
  eq(m:Snapshot().debtRows[1].expiresAt,37.5)
  m:Advance(24)
  eq(m.count,0); eq(m:Debt(),0); eq(#m:Snapshot().debtRows,0)
end)
print("MODEL_TESTS_OK "..tests)
